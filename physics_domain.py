"""
Canonical physics domain models for Project Nebula.

These models establish the resource-transformation foundation while the
legacy identity-vector system remains operational as the current emergent
identity implementation.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Dict, List, Literal, Optional


ResourceFlowType = Literal["consumed", "produced", "accumulated", "transferred"]


@dataclass(frozen=True)
class Resource:
    """A transferable capacity, not an identity or goal."""

    key: str
    label: str
    description: str
    unit: str = "relative"

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class ResourceFlow:
    """A directional movement of one resource within a transformation."""

    resource: str
    amount: float
    flow_type: ResourceFlowType
    confidence: float = 1.0

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class ResourceTransformation:
    """
    Resource input/output metadata generated by a signal.

    In this phase inference is intentionally conservative and rule-based.
    Manual payload metadata can later override or enrich these flows.
    """

    transformation_id: str
    source_signal_id: str
    consumes: List[ResourceFlow] = field(default_factory=list)
    produces: List[ResourceFlow] = field(default_factory=list)
    transfers: List[ResourceFlow] = field(default_factory=list)
    accumulates: List[ResourceFlow] = field(default_factory=list)
    inference_status: str = "rule_based_foundation"

    def to_dict(self) -> dict:
        return {
            "transformation_id": self.transformation_id,
            "source_signal_id": self.source_signal_id,
            "consumes": [flow.to_dict() for flow in self.consumes],
            "produces": [flow.to_dict() for flow in self.produces],
            "transfers": [flow.to_dict() for flow in self.transfers],
            "accumulates": [flow.to_dict() for flow in self.accumulates],
            "inference_status": self.inference_status,
        }


@dataclass(frozen=True)
class Trajectory:
    """A recurring pattern of resource transformations."""

    key: str
    label: str
    description: str
    resource_pattern: Dict[str, List[str]] = field(default_factory=dict)
    linked_identity_field: Optional[str] = None

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class SignalDrift:
    """Immediate displacement generated by one processed signal."""

    magnitude: float
    dynamic_pull: float
    dominant_trajectory: str
    dominant_attractor: str
    vector_space: str

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class IdentityDrift:
    """Accumulated displacement of the emergent identity state through time."""

    global_dominant_identity: str
    global_dominance: Dict[str, float]
    accumulated_vector_dimension: int
    derived_from: str = "aggregated_signal_drift"

    def to_dict(self) -> dict:
        return asdict(self)


