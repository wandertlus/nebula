def resolve_trajectory(category: str, dominant_attractor: str, action_text: str = "") -> str:
    """Map current legacy signal context onto the new trajectory layer."""
    text = action_text.lower()

    if dominant_attractor == "engineering" or category == "Work":
        if any(term in text for term in ("supplier", "lease", "profit", "shop", "business", "customer")):
            return "entrepreneurship"
        return "engineering"
    if dominant_attractor == "be_fluent" or category == "Education":
        return "language_fluency"
    if dominant_attractor == "fitness" or category == "Health":
        return "health"
    if category in {"Distraction", "Void"}:
        return "unstructured_drain"
    if any(term in text for term in ("job", "employment", "salary", "client", "meeting")):
        return "employment"
    return "unclassified"


def infer_resource_transformation(
    event_id: str,
    action_text: str,
    category: str,
    duration: int,
    dominant_trajectory: str,
    effort: float,
    result_value=None,
) -> ResourceTransformation:
    """Create foundational resource metadata for a signal."""
    confidence = 0.55
    minutes = float(max(duration, 0))
    effort_amount = round(max(effort, 0.0), 4)

    consumes = [
        ResourceFlow("time", minutes, "consumed", confidence),
        ResourceFlow("attention", effort_amount, "consumed", confidence),
    ]
    produces: List[ResourceFlow] = []
    accumulates: List[ResourceFlow] = []

    if dominant_trajectory == "engineering":
        produces.append(ResourceFlow("knowledge", effort_amount, "produced", confidence))
    elif dominant_trajectory == "language_fluency":
        produces.append(ResourceFlow("knowledge", effort_amount, "produced", confidence))
    elif dominant_trajectory == "health":
        consumes = [ResourceFlow("time", minutes, "consumed", confidence)]
        produces.extend([
            ResourceFlow("energy", round(effort_amount * 0.8, 4), "produced", confidence),
            ResourceFlow("health_capacity", effort_amount, "produced", confidence),
        ])
    elif dominant_trajectory == "employment":
        consumes.extend([ResourceFlow("energy", effort_amount, "consumed", confidence)])
        produces.extend([
            ResourceFlow("money", 0.0, "produced", confidence),
            ResourceFlow("knowledge", round(effort_amount * 0.5, 4), "produced", confidence),
            ResourceFlow("relationships", round(effort_amount * 0.3, 4), "produced", confidence),
        ])
    elif dominant_trajectory == "entrepreneurship":
        consumes.extend([ResourceFlow("energy", effort_amount, "consumed", confidence)])
        produces.extend([
            ResourceFlow("money", float(result_value or 0.0), "produced", confidence),
            ResourceFlow("knowledge", round(effort_amount * 0.6, 4), "produced", confidence),
            ResourceFlow("relationships", round(effort_amount * 0.4, 4), "produced", confidence),
        ])
    elif dominant_trajectory == "unstructured_drain":
        consumes.extend([ResourceFlow("energy", effort_amount, "consumed", confidence)])
    else:
        accumulates.append(ResourceFlow("knowledge", 0.0, "accumulated", 0.25))

    if result_value is not None and float(result_value) > 0:
        accumulates.append(ResourceFlow("knowledge", float(result_value), "accumulated", confidence))

    return ResourceTransformation(
        transformation_id=f"rt_{event_id}",
        source_signal_id=event_id,
        consumes=consumes,
        produces=produces,
        accumulates=accumulates,
    )


